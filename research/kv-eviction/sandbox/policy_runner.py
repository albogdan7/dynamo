#!/usr/bin/env python3
"""
Isolated policy runner — launched as a child process by the evaluator.

This process has NO access to the simulator or trace modules.
Its sys.path contains only the sandbox directory.

Protocol (line-delimited JSON over stdin/stdout):
  - On startup:  writes {"status": "ready"} or {"status": "error", "msg": "..."}
  - Per eviction: reads one JSON line (list of candidate dicts)
                  writes one JSON line {"victim_id": <int>} or {"victim_id": null, "error": "..."}

DO NOT EDIT THIS FILE.
"""

import sys
import json
import os
import importlib.util

# Only the sandbox directory is on the path — sim/ is never reachable.
SANDBOX_DIR = os.path.dirname(os.path.abspath(__file__))
sys.path = [SANDBOX_DIR]

POLICY_FILE = os.path.join(SANDBOX_DIR, "policy.py")


def _load_policy():
    spec = importlib.util.spec_from_file_location("policy", POLICY_FILE)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    if not hasattr(mod, "EvictionPolicy"):
        raise AttributeError("policy.py must define class EvictionPolicy")
    return mod.EvictionPolicy()


try:
    policy = _load_policy()
    sys.stdout.write(json.dumps({"status": "ready"}) + "\n")
    sys.stdout.flush()
except Exception as exc:
    sys.stdout.write(json.dumps({"status": "error", "msg": str(exc)}) + "\n")
    sys.stdout.flush()
    sys.exit(1)

for raw_line in sys.stdin:
    raw_line = raw_line.strip()
    if not raw_line:
        continue
    try:
        candidates = json.loads(raw_line)
        victim_id = policy.select_victim(candidates)
        sys.stdout.write(json.dumps({"victim_id": victim_id}) + "\n")
    except Exception as exc:
        sys.stdout.write(json.dumps({"victim_id": None, "error": str(exc)}) + "\n")
    sys.stdout.flush()
