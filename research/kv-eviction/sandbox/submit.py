#!/usr/bin/env python3
"""
Evaluate your eviction policy and save results.

Usage
-----
    python submit.py

Results are written to ../results/run_<timestamp>.json

DO NOT EDIT THIS FILE.

ISOLATION MODEL
---------------
policy.py is executed in a separate child process (policy_runner.py).
The child's sys.path contains ONLY the sandbox directory, so it can
never import the simulator, the trace, or any results. All eviction
decisions cross a JSON-over-pipe boundary. The scoring process holds
all trace and simulator state; the policy process sees only the
candidate block lists it is sent.
"""

import sys
import os
import json
import datetime
import subprocess
import threading
import ast

# ---------------------------------------------------------------------------
# Paths — keep sim/ invisible to the policy subprocess
# ---------------------------------------------------------------------------

SANDBOX_DIR   = os.path.dirname(os.path.abspath(__file__))
RESULTS_DIR   = os.path.join(SANDBOX_DIR, "..", "results")
SIM_DIR       = os.path.join(SANDBOX_DIR, "..", "sim")
POLICY_FILE   = os.path.join(SANDBOX_DIR, "policy.py")
RUNNER_SCRIPT = os.path.join(SANDBOX_DIR, "policy_runner.py")

# Sim modules are imported into THIS (scoring) process only.
sys.path.insert(0, os.path.abspath(SIM_DIR))


# ---------------------------------------------------------------------------
# AST-based static check (defense-in-depth; not the isolation boundary)
# ---------------------------------------------------------------------------

_FORBIDDEN_NAMES = {"sim", "cache", "trace", "importlib", "inspect", "gc"}
_FORBIDDEN_BUILTINS = {"eval", "exec", "__import__", "compile", "open"}


def _ast_check(source: str):
    """
    Reject obvious cheating attempts before subprocess launch.
    This is heuristic only — actual isolation is the subprocess boundary.
    """
    try:
        tree = ast.parse(source)
    except SyntaxError as e:
        print(f"\n[ERROR] policy.py has a syntax error:\n  {e}\n")
        sys.exit(1)

    for node in ast.walk(tree):
        # Block imports of forbidden modules.
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            names = (
                [a.name for a in node.names]
                if isinstance(node, ast.Import)
                else ([node.module] if node.module else [])
            )
            for name in names:
                root = (name or "").split(".")[0]
                if root in _FORBIDDEN_NAMES:
                    print(f"\n[DISQUALIFIED] policy.py imports forbidden module '{name}'.\n"
                          "  Only the `blocks` argument to select_victim() may be used.\n")
                    sys.exit(1)

        # Block dangerous builtins.
        if isinstance(node, ast.Call):
            func = node.func
            name = (
                func.id if isinstance(func, ast.Name) else
                func.attr if isinstance(func, ast.Attribute) else None
            )
            if name in _FORBIDDEN_BUILTINS:
                print(f"\n[DISQUALIFIED] policy.py calls forbidden builtin '{name}'.\n")
                sys.exit(1)


# ---------------------------------------------------------------------------
# Subprocess policy wrapper
# ---------------------------------------------------------------------------

class _SubprocessPolicy:
    """
    Runs policy.py in an isolated child process via policy_runner.py.

    The child's sys.path = [sandbox/] only — it cannot import sim/, trace,
    cache, or anything outside the sandbox directory. All communication is
    line-delimited JSON over stdin/stdout.
    """

    CALL_TIMEOUT_S = 5.0

    def __init__(self):
        # Scrub PYTHONPATH so the child cannot import unexpected packages.
        env = os.environ.copy()
        env.pop("PYTHONPATH", None)

        self._proc = subprocess.Popen(
            [sys.executable, "-I", RUNNER_SCRIPT],  # -I: isolated mode
            stdin=subprocess.PIPE,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            env=env,
            cwd=SANDBOX_DIR,
        )

        # Wait for the ready handshake.
        ready_raw = self._proc.stdout.readline()
        try:
            ready = json.loads(ready_raw)
        except Exception:
            print(f"\n[ERROR] policy_runner.py sent unexpected startup output:\n"
                  f"  {ready_raw!r}\n")
            sys.exit(1)

        if ready.get("status") != "ready":
            print(f"\n[ERROR] Policy failed to load:\n  {ready.get('msg', ready_raw)}\n")
            sys.exit(1)

        self.invalid_calls   = 0
        self.timeout_calls   = 0
        self._lock           = threading.Lock()

    def select_victim(self, blocks: list) -> int | None:
        payload = (json.dumps(blocks) + "\n").encode()

        with self._lock:
            try:
                self._proc.stdin.write(payload)
                self._proc.stdin.flush()
            except BrokenPipeError:
                self.invalid_calls += 1
                return None

            # Read with timeout so a hung policy doesn't stall the sim.
            result: list[bytes | None] = [None]

            def _read():
                try:
                    result[0] = self._proc.stdout.readline()
                except Exception:
                    pass

            t = threading.Thread(target=_read, daemon=True)
            t.start()
            t.join(self.CALL_TIMEOUT_S)

            if result[0] is None:
                self.timeout_calls += 1
                return None

            try:
                response = json.loads(result[0])
                victim_id = response.get("victim_id")
                if victim_id is None:
                    self.invalid_calls += 1
                return victim_id
            except Exception:
                self.invalid_calls += 1
                return None

    def close(self):
        try:
            self._proc.stdin.close()
            self._proc.wait(timeout=3)
        except Exception:
            self._proc.kill()


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    print("=" * 60)
    print("  KV Eviction Policy Evaluator")
    print("=" * 60)

    # Static check before launching anything.
    print("\nChecking policy.py  ...", end=" ")
    policy_source = open(POLICY_FILE).read()
    _ast_check(policy_source)
    print("OK")

    # Launch isolated policy subprocess.
    print("Launching policy    ...", end=" ")
    policy = _SubprocessPolicy()
    print("OK")

    # Import sim modules (only in this scoring process).
    from trace import generate_trace
    from cache import run

    # Two independent traces — same shape, different seeds.
    # The agent tunes on seed=42 and is scored on seed=99.
    # They share no token content, so there is nothing to memorize.
    print("Generating traces   ...", end=" ")
    _TRACE_KWARGS = dict(num_sessions=40, turns_per_session=6, repeat_fraction=0.3)
    tuning_trace = generate_trace(**_TRACE_KWARGS, seed=42)
    eval_trace   = generate_trace(**_TRACE_KWARGS, seed=99)
    print(f"OK  ({len(tuning_trace)} tuning / {len(eval_trace)} eval requests)")

    # Tuning run (agent sees these numbers).
    print("\nRunning on TUNING trace  ...", end=" ")
    tuning_metrics = run(tuning_trace, policy, capacity_blocks=256)
    print("done")

    # Eval run (held-out true score).
    print("Running on EVAL trace    ...", end=" ")
    eval_metrics = run(eval_trace, policy, capacity_blocks=256)
    print("done")

    policy.close()

    # Attach subprocess-level counters.
    for m in (tuning_metrics, eval_metrics):
        m["policy_timeout_calls"] = policy.timeout_calls
        m["policy_invalid_calls"] = policy.invalid_calls

    # Print summary.
    print("\n" + "-" * 60)
    print("  TUNING results (iterate on your policy using these)")
    print("-" * 60)
    _print_metrics(tuning_metrics)

    print("\n" + "-" * 60)
    print("  EVAL results   (held-out — your true score)")
    print("-" * 60)
    _print_metrics(eval_metrics)

    if policy.timeout_calls:
        print(f"\n[WARN] select_victim() timed out {policy.timeout_calls}x "
              f"(>{_SubprocessPolicy.CALL_TIMEOUT_S}s) — fell back to LRU.")
    if policy.invalid_calls:
        print(f"\n[WARN] select_victim() returned an invalid block_id "
              f"{policy.invalid_calls}x — fell back to LRU.")

    # Save results.
    os.makedirs(RESULTS_DIR, exist_ok=True)
    ts = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    out_path = os.path.join(RESULTS_DIR, f"run_{ts}.json")
    record = {
        "timestamp":     ts,
        "policy_source": policy_source,
        "tuning":        tuning_metrics,
        "eval":          eval_metrics,
    }
    with open(out_path, "w") as f:
        json.dump(record, f, indent=2)

    print(f"\nResults saved → {os.path.relpath(out_path, SANDBOX_DIR)}")
    print("=" * 60)


def _print_metrics(m: dict):
    print(f"  Requests          : {m['num_requests']}")
    print(f"  Cache hit rate    : {m['overall_hit_rate']:.1%}")
    print(f"  Mean TTFT         : {m['mean_ttft_ms']:.1f} ms")
    print(f"  p95  TTFT         : {m['p95_ttft_ms']:.1f} ms")
    print(f"  p99  TTFT         : {m['p99_ttft_ms']:.1f} ms")
    print(f"  Evictions         : {m['evictions']}")
    print(f"  Sim throughput    : {m['sim_throughput_rps']:.1f} req/s")


if __name__ == "__main__":
    main()
