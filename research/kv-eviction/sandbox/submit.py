#!/usr/bin/env python3
"""
Evaluate your eviction policy and save results.

Usage
-----
    python submit.py

Results are written to results/run_<timestamp>.json
Read that file (or just look at the summary printed here) to see how your
policy performed.

DO NOT EDIT THIS FILE.
"""

import sys
import os
import json
import datetime
import importlib.util
import traceback

# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------

SANDBOX_DIR = os.path.dirname(os.path.abspath(__file__))
RESULTS_DIR = os.path.join(SANDBOX_DIR, "results")
SIM_DIR     = os.path.join(SANDBOX_DIR, "..", "sim")
POLICY_FILE = os.path.join(SANDBOX_DIR, "policy.py")

sys.path.insert(0, os.path.abspath(SIM_DIR))


# ---------------------------------------------------------------------------
# Load policy from policy.py
# ---------------------------------------------------------------------------

def load_policy():
    spec = importlib.util.spec_from_file_location("policy", POLICY_FILE)
    module = importlib.util.module_from_spec(spec)
    try:
        spec.loader.exec_module(module)
    except Exception as e:
        print(f"\n[ERROR] Failed to import policy.py:\n  {e}\n")
        traceback.print_exc()
        sys.exit(1)

    if not hasattr(module, "EvictionPolicy"):
        print("\n[ERROR] policy.py must define a class called EvictionPolicy\n")
        sys.exit(1)

    try:
        policy = module.EvictionPolicy()
    except Exception as e:
        print(f"\n[ERROR] Could not instantiate EvictionPolicy:\n  {e}\n")
        sys.exit(1)

    if not callable(getattr(policy, "select_victim", None)):
        print("\n[ERROR] EvictionPolicy must have a select_victim(blocks) method\n")
        sys.exit(1)

    return policy, open(POLICY_FILE).read()


# ---------------------------------------------------------------------------
# Sandbox check: make sure policy doesn't access trace or sim internals
# ---------------------------------------------------------------------------

def _make_safe_policy(policy):
    """Wrap policy so crashes don't kill the whole run."""
    class SafePolicy:
        def select_victim(self, blocks):
            try:
                result = policy.select_victim(blocks)
                # Must return a valid block_id
                valid_ids = {b["block_id"] for b in blocks}
                if result not in valid_ids:
                    return None  # cache.py falls back to LRU
                return result
            except Exception:
                return None
    return SafePolicy()


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    print("=" * 60)
    print("  KV Eviction Policy Evaluator")
    print("=" * 60)

    # Load policy
    print("\nLoading policy.py ...", end=" ")
    policy, policy_source = load_policy()
    safe_policy = _make_safe_policy(policy)
    print("OK")

    # Import sim
    from trace import generate_trace, split_trace
    from cache import run

    # Generate trace and split
    print("Generating trace    ...", end=" ")
    full_trace = generate_trace(
        num_sessions=40,
        turns_per_session=6,
        repeat_fraction=0.3,
        seed=42,
    )
    tuning_trace, eval_trace = split_trace(full_trace, eval_fraction=0.5)
    print(f"OK  ({len(tuning_trace)} tuning / {len(eval_trace)} eval requests)")

    # Run on tuning half (what the agent sees during iteration)
    print("\nRunning on TUNING trace  ...", end=" ")
    tuning_metrics = run(tuning_trace, safe_policy, capacity_blocks=256)
    print("done")

    # Run on eval half (held-out, used for final scoring)
    print("Running on EVAL trace    ...", end=" ")
    eval_metrics = run(eval_trace, safe_policy, capacity_blocks=256)
    print("done")

    # Print summary
    print("\n" + "-" * 60)
    print("  TUNING results (use these to iterate on your policy)")
    print("-" * 60)
    _print_metrics(tuning_metrics)

    print("\n" + "-" * 60)
    print("  EVAL results   (held-out — your true score)")
    print("-" * 60)
    _print_metrics(eval_metrics)

    if tuning_metrics["invalid_policy_fallbacks"] > 0:
        print(f"\n[WARN] Policy returned invalid block_id {tuning_metrics['invalid_policy_fallbacks']} times"
              f" — fell back to LRU. Fix select_victim() to always return a valid block_id.")

    # Write results
    os.makedirs(RESULTS_DIR, exist_ok=True)
    ts = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    out_path = os.path.join(RESULTS_DIR, f"run_{ts}.json")

    record = {
        "timestamp": ts,
        "policy_source": policy_source,
        "tuning": tuning_metrics,
        "eval":   eval_metrics,
    }
    with open(out_path, "w") as f:
        json.dump(record, f, indent=2)

    print(f"\nResults saved → {os.path.relpath(out_path, SANDBOX_DIR)}")
    print("=" * 60)


def _print_metrics(m: dict):
    print(f"  Requests          : {m['num_requests']}")
    print(f"  Cache hit rate    : {m['overall_hit_rate']:.1%}")
    print(f"  Mean TTFT         : {m['mean_ttft_ms']:.1f} ms")
    print(f"  p95  TTFT         : {m['p95_ttft_ms']:.1f} ms")
    print(f"  p99  TTFT         : {m['p99_ttft_ms']:.1f} ms")
    print(f"  Evictions         : {m['evictions']}")
    print(f"  Sim throughput    : {m['sim_throughput_rps']:.1f} req/s")


if __name__ == "__main__":
    main()
